param(
  [string]$ManifestPath = '',
  [string]$OntologyPath = '',
  [string]$SnapshotPath = '',
  [string]$OfflineResultPath = '',
  [string]$OutPath = ''
)
# Generates the capability/limitation status document from machine-readable
# sources so the README cannot drift from the manifest, ontology and latest
# snapshot/test evidence.
$ErrorActionPreference = 'Stop'
$scriptsRoot = Split-Path -Parent $PSScriptRoot
$skillRoot = Split-Path -Parent $scriptsRoot
if (-not $ManifestPath) { $ManifestPath = Join-Path $scriptsRoot 'script_manifest.json' }
if (-not $OntologyPath) { $OntologyPath = Join-Path $skillRoot 'assets\ontology.json' }
if (-not $OutPath) { $OutPath = Join-Path $skillRoot 'references\capability-status.generated.md' }
$manifest = Get-Content -Raw -LiteralPath $ManifestPath -Encoding UTF8 | ConvertFrom-Json
$ontology = Get-Content -Raw -LiteralPath $OntologyPath -Encoding UTF8 | ConvertFrom-Json
$scriptCount = 0
foreach ($class in @($manifest.classes.PSObject.Properties)) { $scriptCount += @($class.Value).Count }
$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('# KV Studio Operator capability status (generated)')
$lines.Add('')
$lines.Add('> Generated by `scripts/workflow_tools/generate_kv_capability_report.ps1`. Do not edit by hand.')
$lines.Add("> Generated at: $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss zzz')")
$lines.Add('')
$lines.Add('## Sources')
$lines.Add('')
$lines.Add("- manifest: ``$([IO.Path]::GetFileName($ManifestPath))`` ($scriptCount scripts)")
$lines.Add("- ontology: ``$([IO.Path]::GetFileName($OntologyPath))`` ($(@($ontology.assets.PSObject.Properties).Count) assets)")
if ($SnapshotPath) { $lines.Add("- snapshot: ``$SnapshotPath``") }
$lines.Add('')
$lines.Add('## Offline tests')
$lines.Add('')
if ($OfflineResultPath -and (Test-Path -LiteralPath $OfflineResultPath -PathType Leaf)) {
  $offline = Get-Content -Raw -LiteralPath $OfflineResultPath -Encoding UTF8 | ConvertFrom-Json
  $lines.Add("- result: ``$OfflineResultPath``")
  $lines.Add("- suites: $($offline.suites_passed)/$($offline.suites_total) passed, cases: $($offline.cases_passed) passed / $($offline.cases_failed) failed")
  $lines.Add("- generated: $($offline.generated_at)")
  $lines.Add('- live UI is **not** covered by this run.')
} else {
  $lines.Add('- no offline result file supplied.')
}
$lines.Add('')
$lines.Add('## Live acceptance')
$lines.Add('')
$livePath = Join-Path $skillRoot 'tests\live_acceptance\latest.json'
if (Test-Path -LiteralPath $livePath -PathType Leaf) {
  $live = Get-Content -Raw -LiteralPath $livePath -Encoding UTF8 | ConvertFrom-Json
  $lines.Add("- recorded at: $($live.recorded_at)")
  $lines.Add("- snapshot run: ``$($live.run_dir)``")
  $lines.Add("- snapshot status: $($live.snapshot_status); stages ok: $($live.stage_ok)/$($live.stage_total)")
  $lines.Add("- KVS version: $($live.kvs_version); OS: $($live.os)")
  $lines.Add("- readiness: automated=$($live.ready_for_full_1_to_1_import), manual=$($live.ready_for_manual_1_to_1_rebuild)")
  $lines.Add("- blocking gaps: $((@($live.blocking_gaps) -join ', '))")
} else {
  $lines.Add('- no live acceptance record; run `tests/live-acceptance/run.ps1 -Record` on the target KV STUDIO machine.')
}
$lines.Add('')
$lines.Add('## Snapshot readiness')
$lines.Add('')
if ($SnapshotPath) {
  $manifestPath = Join-Path $SnapshotPath 'source_snapshot_manifest.json'
  $inventoryPath = Join-Path $SnapshotPath 'text\project_inventory.json'
  if (Test-Path -LiteralPath $manifestPath -PathType Leaf) {
    $snap = Get-Content -Raw -LiteralPath $manifestPath -Encoding UTF8 | ConvertFrom-Json
    $lines.Add("- status: $($snap.status); missing capabilities: $((@($snap.missing_capabilities) -join ', '))")
  }
  if (Test-Path -LiteralPath $inventoryPath -PathType Leaf) {
    $inv = Get-Content -Raw -LiteralPath $inventoryPath -Encoding UTF8 | ConvertFrom-Json
    $gaps = @($inv.clone_readiness.blocking_gaps | ForEach-Object { $_.id }) -join ', '
    $lines.Add("- automated 1:1: $($inv.clone_readiness.ready_for_full_1_to_1_import); manual rebuild: $($inv.clone_readiness.ready_for_manual_1_to_1_rebuild)")
    $lines.Add("- blocking gaps: $gaps")
  }
} else {
  $lines.Add('- no snapshot path supplied.')
}
$lines.Add('')
$lines.Add('## Assets')
$lines.Add('')
$lines.Add('| asset | status | artifact |')
$lines.Add('| --- | --- | --- |')
foreach ($asset in @($ontology.assets.PSObject.Properties | Sort-Object Name)) {
  $status = [string]$asset.Value.snapshot_status
  $artifact = [string]$asset.Value.snapshot_artifact
  $lines.Add("| $($asset.Name) | $status | $artifact |")
}
$lines.Add('')
$lines.Add('## Known boundaries')
$lines.Add('')
$lines.Add('- `ethercat_device_parameters` is screenshot-only: clipboard/UIA/MSAA/export/OCR all fail; this is documented in the ontology `limited_reason`.')
$lines.Add('- Offline suites do not drive KV STUDIO; live suites and `13_project_text_snapshot` must be run on the target machine.')
$lines.Add('- CPU expansion units are absent in the sample project (only `[0] KV-X520`); KV-EC01 is an EtherCAT slave, not an expansion unit.')
New-Item -ItemType Directory -Force -Path (Split-Path -Parent $OutPath) | Out-Null
[IO.File]::WriteAllLines($OutPath, $lines, (New-Object Text.UTF8Encoding($false)))
Write-Host "GENERATED: $OutPath ($($lines.Count) lines)"
